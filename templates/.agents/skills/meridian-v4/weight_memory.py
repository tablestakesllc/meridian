def _find_repo_root() -> Path:
    """Locate the Meridian repo root by walking up from this file.

    Identifies the root by the presence of agent_docs/MEMORY_INDEX.yaml.
    Cross-platform (pathlib), agent-agnostic, and robust to script relocation
    or multi-root workspaces — matches only the repo that owns this index.
    """
    sentinel = Path("agent_docs") / "MEMORY_INDEX.yaml"
    here = Path(__file__).resolve().parent
    for candidate in [here, *here.parents]:
        if (candidate / sentinel).exists():
            return candidate
    raise RuntimeError(
        f"Cannot locate Meridian repo root from {here}. "
        f"Expected to find '{sentinel}' in an ancestor directory."
    )


REPO_ROOT = _find_repo_root()
INDEX_PATH = REPO_ROOT / "agent_docs" / "MEMORY_INDEX.yaml"
DEFAULTS_PATH = REPO_ROOT / "agent_docs" / "weights.default.yaml"
AGENT_DIR = REPO_ROOT / ".agent"
WEIGHTS_PATH = AGENT_DIR / "weights.yaml"
L1_PATH = REPO_ROOT / "agent_docs" / "L1_CONTEXT.md"

# All files that may contain annotated block content
BLOCK_SOURCES = [
    REPO_ROOT / "agent_docs" / "MEMORY.md",
    *sorted((REPO_ROOT / ".agents" / "skills").glob("*/SKILL.md")),
]

BLOCK_START_RE = re.compile(r"<!--\s*block:\s*(\S+?)\s*[\|>]")
BLOCK_END_RE = re.compile(r"<!--\s*/block\s*-->")
L1_SUMMARY_END_RE = re.compile(r"<!--\s*/l1-summary\s*-->")

L1_HEADER = """\
# Meridian — L1 Hot-Load Context ({meridian_version})

> **Auto-generated at session-end.** Contains the full content of all L1-tier memory blocks.
> Do NOT edit manually. Regenerated by `.agents/skills/meridian-v4/weight_memory.py` as a side effect of weight updates.
> Source blocks are in `agent_docs/MEMORY.md` and `.agents/skills/*/SKILL.md`.
> This file is gitignored — per-developer only.
>
> L1 threshold: weight >= {l1_thresh:.1f}. Current L1 blocks: {count}

"""


# ── Helpers ───────────────────────────────────────────────────────────────────

def _require_yaml() -> None:
    if not _HAS_YAML:
        print("ERROR: PyYAML not installed. Run: pip install pyyaml", file=sys.stderr)
        sys.exit(1)


def load_yaml(path: Path) -> dict:
    _require_yaml()
    if not path.exists():
        print(f"ERROR: {path} not found", file=sys.stderr)
        sys.exit(1)
    with path.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def save_yaml(data: dict, path: Path, header: str = "") -> None:
    _require_yaml()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        if header:
            f.write(header)
        yaml.dump(data, f, default_flow_style=False, allow_unicode=True, sort_keys=False)


def get_git_user() -> tuple[str, str]:
    """Return (name, email) from git config, falling back to empty strings."""
    def _get(key: str) -> str:
        try:
            return subprocess.check_output(
                ["git", "config", key], text=True, stderr=subprocess.DEVNULL
            ).strip()
        except (subprocess.CalledProcessError, FileNotFoundError):
            return ""
    return _get("user.name"), _get("user.email")


def classify_tier(weight: float, l1_thresh: float, archive_thresh: float) -> str:
    if weight >= l1_thresh:
        return "L1"
    if weight < archive_thresh:
        return "ARCHIVE"
    return "L2"


def parse_ids(raw: str) -> set[str]:
    if not raw:
        return set()
    return {s.strip() for s in raw.split(",") if s.strip()}


def match_files_from_git(index_blocks: list, repo_root: Path) -> set[str]:
    """Return block IDs whose files: globs match any git-modified file this session.

    Calls ``git diff --name-only @{u}..HEAD`` to get files changed in commits
    since the upstream (i.e. the session's committed work).  Falls back to
    ``git diff --name-only HEAD`` (uncommitted changes) when no upstream is
    configured (e.g. fresh local branch, CI environment, or detached HEAD).

    fnmatch-matches each block's ``files:`` globs against repo-relative paths.
    Blocks with ``files: []`` or no ``files:`` field are skipped.
    """
    try:
        result = subprocess.run(
            ["git", "diff", "--name-only", "@{u}..HEAD"],
            capture_output=True, text=True, cwd=repo_root,
        )
        if result.returncode != 0:
            # No upstream configured — fall back to uncommitted working-tree diff
            result = subprocess.run(
                ["git", "diff", "--name-only", "HEAD"],
                capture_output=True, text=True, cwd=repo_root,
            )
        modified = set(result.stdout.strip().splitlines())
    except (subprocess.CalledProcessError, FileNotFoundError):
        return set()

    if not modified:
        return set()

    matched: set[str] = set()
    for block in index_blocks:
        globs = block.get("files") or []
        if not globs:
            continue
        bid = block.get("id", "")
        for pattern in globs:
            if any(fnmatch.fnmatch(f, pattern) for f in modified):
                matched.add(bid)
                break
    return matched


def resolve_deps(loaded_ids: set[str], index_blocks: list) -> tuple[set[str], list[tuple[str, str]]]:
    """Transitively expand loaded_ids by following depends: fields.

    Returns (expanded_set, [(dep_id, parent_id), ...]) listing auto-included deps.
    Cycle-safe: each block ID is visited at most once.
    Auto-added deps get the loaded (0.00) delta — NOT the used (+0.10) delta.
    """
    index_map = {b.get("id", ""): b for b in index_blocks}
    auto_included: list[tuple[str, str]] = []
    visited: set[str] = set(loaded_ids)
    queue: list[tuple[str, str]] = [(bid, "") for bid in loaded_ids]

    while queue:
        current_id, _ = queue.pop(0)
        block = index_map.get(current_id)
        if not block:
            continue
        for dep_id in (block.get("depends") or []):
            if dep_id and dep_id not in visited and dep_id in index_map:
                visited.add(dep_id)
                auto_included.append((dep_id, current_id))
                queue.append((dep_id, current_id))

    return visited, auto_included


def load_thresholds(defaults_data: dict) -> tuple[float, float, dict]:
    meta = defaults_data.get("meta", {})
    t = meta.get("thresholds", {})
    d = meta.get("delta", {})
    return float(t.get("l1", 8.0)), float(t.get("archive", 2.0)), d


def _preview_l1_blocks(weights_data: dict, index_blocks: list, l1_thresh: float) -> None:
    """Print a compact L1 preview table for --dry-run mode.

    Pulls block metadata from MEMORY_INDEX (skill, summary, tags) rather than
    raw block content. Sorted by descending weight.
    """
    index_map = {b.get("id", ""): b for b in index_blocks}
    l1_blocks = sorted(
        [b for b in weights_data.get("blocks", []) if float(b.get("weight", 0)) >= l1_thresh],
        key=lambda b: -float(b["weight"]),
    )
    print("\n  --- DRY-RUN L1 PREVIEW ---")
    print(f"  Blocks that WOULD load into L1 after this update ({len(l1_blocks)} at weight >= {l1_thresh:.1f}):")
    for b in l1_blocks:
        bid = b["id"]
        meta = index_map.get(bid, {})
        skill = meta.get("skill") or "?"
        summary = (meta.get("summary") or "(no summary)")[:60]
        tags = (meta.get("tags") or [])[:4]
        triggers = ", ".join(tags) if tags else "(none)"
        print(f"    {bid:40s}  skill: {skill:25s}  weight: {b['weight']:.2f}")
        print(f"      Summary: {summary}")
        print(f"      Top triggers: {triggers}")


# ── Block content extraction ──────────────────────────────────────────────────

def extract_block_content(block_id: str) -> str | None:
    """Scan annotated source files for block_id. Return its L1 content.

    If the block contains a <!-- /l1-summary --> marker, only content above
    the marker is returned (with a synthetic <!-- /block --> close tag appended).
    Content below the marker stays in the source file as reference-only and is
    never emitted into L1_CONTEXT.md.

    Blocks without the marker behave identically to before: everything between
    <!-- block: ID --> and <!-- /block --> is returned verbatim.
    """
    for source_file in BLOCK_SOURCES:
        if not source_file.exists():
            continue
        lines = source_file.read_text(encoding="utf-8").splitlines(keepends=True)
        in_block = False
        collected: list[str] = []
        summary_closed = False
        for line in lines:
            if not in_block:
                m = BLOCK_START_RE.search(line)
                if m and m.group(1) == block_id:
                    in_block = True
                    collected.append(line)
            else:
                if L1_SUMMARY_END_RE.search(line):
                    summary_closed = True
                    continue  # skip the marker line itself
                if BLOCK_END_RE.search(line):
                    if summary_closed:
                        # Return only content above the marker with synthetic close tag
                        return "\n".join(["".join(collected).rstrip(), "<!-- /block -->"])
                    else:
                        collected.append(line)
                        return "".join(collected).rstrip()
                if not summary_closed:
                    collected.append(line)
    return None


# ── L1_CONTEXT.md generation ──────────────────────────────────────────────────

def _generate_routing_table(index_blocks: list) -> str:
    """Build a File → Skill routing table from MEMORY_INDEX files: globs.

    For each block with a non-null skill and at least one files: glob, emits one
    table row per (pattern, skill) combination.  Multiple blocks that share the
    same glob but point to different skills produce one row listing all skills.
    Blocks with skill=None (L1 auto-load blocks) and blocks with files=[] are
    skipped.  Result is a markdown string ready to append to L1_CONTEXT.md.
    Returns an empty string when no blocks carry file globs.
    """
    pattern_skills: dict[str, set[str]] = {}
    for block in index_blocks:
        skill = block.get("skill")
        if not skill:
            continue
        for pattern in (block.get("files") or []):
            if pattern:
                pattern_skills.setdefault(pattern, set()).add(skill)

    if not pattern_skills:
        return ""

    lines = [
        "\n---\n",
        "## File \u2192 Skill Routing Table\n",
        "> Auto-generated from `files:` globs in `agent_docs/MEMORY_INDEX.yaml`.",
        "> Regenerated at session-end by `weight_memory.py`. Do NOT edit manually.",
        "> When opening a file during a task, match against this table and",
        "> `read_file` the listed skill(s) before proceeding.\n",
        "| File pattern | Skill(s) to load |",
        "|---|---|",
    ]
    for pattern in sorted(pattern_skills):
        skills = ", ".join(f"`{s}`" for s in sorted(pattern_skills[pattern]))
        lines.append(f"| `{pattern}` | {skills} |")
    lines.append("")
    return "\n".join(lines)


def _update_weight_in_block_header(content: str, weight: float) -> str:
    """Update the weight annotation in a block start comment."""
    return re.sub(
        r"(<!--\s*block:[^>]*\|\s*weight:\s*)[\d.]+",
        lambda m: f"{m.group(1)}{weight:.2f}",
        content,
        count=1,
    )


def generate_l1_context(
    weights_data: dict, l1_thresh: float, dry_run: bool = False
) -> list[str]:
    """
    Regenerate agent_docs/L1_CONTEXT.md from all blocks at weight >= l1_thresh.
    Returns list of block IDs whose content could not be located in source files.
    """
    l1_blocks = sorted(
        [b for b in weights_data.get("blocks", []) if float(b.get("weight", 0)) >= l1_thresh],
        key=lambda b: -float(b["weight"]),
    )
    sections: list[str] = []
    missing: list[str] = []
    for block in l1_blocks:
        bid = block["id"]
        content = extract_block_content(bid)
        if content:
            content = _update_weight_in_block_header(content, float(block["weight"]))
            sections.append(content)
        else:
            missing.append(bid)

    defaults_data = yaml.safe_load(DEFAULTS_PATH.read_text(encoding="utf-8")) or {} if _HAS_YAML else {}
    meridian_version = defaults_data.get("meta", {}).get("meridian_version", "unknown")
    header = L1_HEADER.format(meridian_version=meridian_version, l1_thresh=l1_thresh, count=len(l1_blocks))
    body = "\n\n---\n\n".join(sections)

    # Routing table — derived from MEMORY_INDEX files: globs (always current)
    index_blocks: list = []
    if INDEX_PATH.exists() and _HAS_YAML:
        index_data = yaml.safe_load(INDEX_PATH.read_text(encoding="utf-8")) or {}
        index_blocks = index_data.get("blocks", [])
    routing_table = _generate_routing_table(index_blocks)

    full = header + body + routing_table + "\n"
    if not dry_run:
        L1_PATH.write_text(full, encoding="utf-8")
    return missing


# ── Merge driver bootstrap (Item 9) ──────────────────────────────────────────

_GITCONFIG_CONTENT = """\
[merge "union"]
\tname = union merge driver
\tdriver = git merge-file --union %O %A %B
"""

_GITATTRIBUTES_CONTENT = """\
# Meridian memory files — use union merge driver to prevent conflicts
.agent/**/*.yaml      merge=union
.agents/**/*.yaml     merge=union
agent_docs/**/*.yaml  merge=union
"""


def _bootstrap_merge_driver() -> None:
    """Create .gitconfig and .gitattributes for union merge driver if absent.

    Registers the driver locally via ``git config --local include.path``.
    Idempotent — skips creation if files already exist.  Called by --seed.
    """
    # .gitconfig — driver definition
    gitconfig_path = REPO_ROOT / ".gitconfig"
    if not gitconfig_path.exists():
        gitconfig_path.write_text(_GITCONFIG_CONTENT)
        print(f"  Created {gitconfig_path.relative_to(REPO_ROOT)}")
    else:
        print(f"  {gitconfig_path.relative_to(REPO_ROOT)} already exists — skipped")

    # .gitattributes — path scope
    gitattributes_path = REPO_ROOT / ".gitattributes"
    if not gitattributes_path.exists():
        gitattributes_path.write_text(_GITATTRIBUTES_CONTENT)
        print(f"  Created {gitattributes_path.relative_to(REPO_ROOT)}")
    else:
        print(f"  {gitattributes_path.relative_to(REPO_ROOT)} already exists — skipped")

    # Wire the include — idempotent (git config --local replaces existing value)
    try:
        subprocess.run(
            ["git", "config", "--local", "include.path", "../.gitconfig"],
            cwd=REPO_ROOT,
            capture_output=True,
            check=True,
        )
        print("  git config --local include.path set")
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        print(f"  WARNING: could not set git config include.path: {exc}", file=sys.stderr)


# ── --seed ───────────────────────────────────────────────────────────────────

def cmd_seed(dry_run: bool) -> None:
    """Create .agent/weights.yaml from weights.default.yaml (first-boot)."""
    if WEIGHTS_PATH.exists():
        print("  .agent/weights.yaml already exists.")
        print("  To reseed from defaults (DESTRUCTIVE), delete it first.")
        return
    defaults = load_yaml(DEFAULTS_PATH)
    l1_thresh, archive_thresh, _ = load_thresholds(defaults)
    name, email = get_git_user()
    today = str(date.today())

    weights_blocks = []
    for b in defaults.get("blocks", []):
        w = round(float(b.get("seed_weight", 5.0)), 2)
        weights_blocks.append({
            "id": b["id"],
            "weight": w,
            "tier": classify_tier(w, l1_thresh, archive_thresh),
            "last_used": None,
        })

    weights_data = {
        "meta": {
            "schema_version": 1,
            "author": name,
            "author_email": email,
            "last_updated_by": name,
            "last_updated": today,
            "seeded_from": "agent_docs/weights.default.yaml",
            "seeded_date": today,
            "thresholds": {
                "l1": float(defaults.get("meta", {}).get("thresholds", {}).get("l1", 8.0)),
                "archive": float(defaults.get("meta", {}).get("thresholds", {}).get("archive", 2.0)),
            },
            "delta": {
                "loaded_used": float(defaults.get("meta", {}).get("delta", {}).get("loaded_used", 0.10)),
                "loaded_skipped": float(defaults.get("meta", {}).get("delta", {}).get("loaded_skipped", 0.00)),
                "not_loaded": float(defaults.get("meta", {}).get("delta", {}).get("not_loaded", -0.05)),
            },
            "maintenance_interval": int(defaults.get("meta", {}).get("maintenance_interval", 30)),
            "sessions_since_maintenance": 0,
            "maintenance_deferred": None,
        },
        "blocks": weights_blocks,
    }

    print(f"\n{'DRY RUN — ' if dry_run else ''}Meridian Memory Weight Manager v4.1 — seed")
    if not dry_run:
        save_yaml(
            weights_data, WEIGHTS_PATH,
            "# Meridian per-developer block weights — gitignored, never committed\n"
            "# Seeded from agent_docs/weights.default.yaml; diverges through usage\n#\n",
        )
        print(f"  Created .agent/weights.yaml ({len(weights_blocks)} blocks)")
        if not L1_PATH.exists():
            print("  Generating agent_docs/L1_CONTEXT.md from seeded L1 blocks...")
            missing = generate_l1_context(weights_data, l1_thresh)
            l1_count = sum(1 for b in weights_blocks if b["tier"] == "L1")
            print(f"  Created agent_docs/L1_CONTEXT.md ({l1_count} L1 blocks)")
            _report_missing_l1_content(missing)
        _bootstrap_merge_driver()
        print("  Calibrating export thresholds from git activity...")
        cmd_calibrate(dry_run=False)
    else:
        l1_count = sum(
            1 for b in weights_blocks
            if classify_tier(b["weight"], l1_thresh, archive_thresh) == "L1"
        )
        print(f"  Would create .agent/weights.yaml ({len(weights_blocks)} blocks, {l1_count} L1)")

    _check_defaults_new_blocks(defaults, {"blocks": weights_blocks})
    print()


# ── --generate-l1 ─────────────────────────────────────────────────────────────

def cmd_generate_l1(dry_run: bool) -> None:
    """Regenerate L1_CONTEXT.md from current weights without updating weights."""
    print(f"\n{'DRY RUN — ' if dry_run else ''}Meridian Memory Weight Manager v4.1 — generate-l1")
    if not WEIGHTS_PATH.exists():
        print("  .agent/weights.yaml not found — run --seed first.")
        return
    weights = load_yaml(WEIGHTS_PATH)
    defaults = load_yaml(DEFAULTS_PATH)
    l1_thresh, _, _ = load_thresholds(defaults)
    l1_count = sum(1 for b in weights.get("blocks", []) if float(b.get("weight", 0)) >= l1_thresh)
    missing = generate_l1_context(weights, l1_thresh, dry_run=dry_run)
    action = "Would regenerate" if dry_run else "Regenerated"
    print(f"  {action} agent_docs/L1_CONTEXT.md ({l1_count} L1 blocks)")
    _report_missing_l1_content(missing)
    print()


# ── --check-defaults ──────────────────────────────────────────────────────────

def cmd_check_defaults() -> None:
    """Diff local weights against defaults; print recommendations."""
    print("\nMeridian Memory Weight Manager v4.1 — check-defaults")
    if not WEIGHTS_PATH.exists():
        print("  .agent/weights.yaml not found — run --seed first.")
        return
    defaults = load_yaml(DEFAULTS_PATH)
    weights = load_yaml(WEIGHTS_PATH)
    _check_defaults_new_blocks(defaults, weights)
    print()


def _check_defaults_new_blocks(defaults: dict, weights: dict) -> None:
    default_map = {b["id"]: b for b in defaults.get("blocks", [])}
    local_ids = {b["id"] for b in weights.get("blocks", [])}
    new_blocks = [bid for bid in default_map if bid not in local_ids]
    if new_blocks:
        print(f"\n  RECOMMENDATIONS — {len(new_blocks)} block(s) in defaults not in your weights:")
        for bid in new_blocks:
            b = default_map[bid]
            line = f"    + {bid:45s}  seed={b.get('seed_weight', 5.0):.1f}  [{b.get('category', 'general')}]"
            reason = b.get("reason", "")
            print(line)
            if reason:
                print(f"      {reason}")
        print("  Run --seed (after deleting .agent/weights.yaml) to absorb all defaults.")
    else:
        print("  No new blocks in defaults — your weights file is current.")

    # Threshold diff (Item 3) — compare meta.thresholds and meta.delta
    def_meta = defaults.get("meta", {})
    loc_meta = weights.get("meta", {})
    def_thresh = def_meta.get("thresholds", {})
    def_delta = def_meta.get("delta", {})
    loc_thresh = loc_meta.get("thresholds", {})
    loc_delta = loc_meta.get("delta", {})

    threshold_keys: dict[str, tuple] = {
        "thresholds.l1":          (def_thresh.get("l1"),           loc_thresh.get("l1")),
        "thresholds.archive":     (def_thresh.get("archive"),      loc_thresh.get("archive")),
        "delta.loaded_used":      (def_delta.get("loaded_used"),   loc_delta.get("loaded_used")),
        "delta.loaded_skipped":   (def_delta.get("loaded_skipped"), loc_delta.get("loaded_skipped")),
        "delta.not_loaded":       (def_delta.get("not_loaded"),    loc_delta.get("not_loaded")),
    }
    mismatches = {
        k: (dv, lv)
        for k, (dv, lv) in threshold_keys.items()
        if dv is not None and lv is not None and float(dv) != float(lv)
    }
    if mismatches:
        print(f"\n  THRESHOLD MISMATCH — {len(mismatches)} key(s) differ from maintainer defaults:")
        for key, (def_val, loc_val) in mismatches.items():
            print(f"    {key:30s}  default={def_val}  local={loc_val}")
        print()
        print("  Your weight thresholds differ from the maintainer defaults.")
        print("  Run --seed to reset to defaults, or confirm you intend to keep your local values.")
        print("  [Y to keep / N to reseed]")


def _report_missing_l1_content(missing: list[str]) -> None:
    if missing:
        print(f"\n  ACTION REQUIRED — content not found for {len(missing)} L1 block(s):")
        for bid in missing:
            print(f"    + Add block '{bid}' content to agent_docs/L1_CONTEXT.md manually")
        print("  These blocks are at L1 weight but have no <!-- block: --> annotation in any source file.")


# ── --migrate ─────────────────────────────────────────────────────────────────

def cmd_migrate(dry_run: bool) -> None:
    """
    One-time migration: v4 (weights in MEMORY_INDEX.yaml) → v4.1 (weights in .agent/).

    - Reads weight/tier/last_used from MEMORY_INDEX.yaml
    - Creates .agent/weights.yaml preserving earned weight history
    - Strips weight/tier/last_used from all MEMORY_INDEX.yaml blocks
    - Updates MEMORY_INDEX.yaml meta to format_version 4.1
    """
    print(f"\n{'DRY RUN — ' if dry_run else ''}Meridian Memory Weight Manager v4.1 — migrate")
    index = load_yaml(INDEX_PATH)
    fmt = index.get("meta", {}).get("format_version", 4)
    if fmt >= 4.1:
        print(f"  MEMORY_INDEX.yaml is already format_version {fmt} — nothing to migrate.")
        return

    blocks = index.get("blocks", [])
    old_meta = index.get("meta", {})
    thresholds = old_meta.get("thresholds", {})
    l1_thresh = float(thresholds.get("l1", 8.0))
    archive_thresh = float(thresholds.get("archive", 2.0))
    name, email = get_git_user()
    today = str(date.today())

    # Build weights.yaml from current MEMORY_INDEX values (preserve earned history)
    skip_weights = WEIGHTS_PATH.exists()
    if not skip_weights:
        weights_blocks = []
        for b in blocks:
            w = round(float(b.get("weight", 5.0)), 2)
            weights_blocks.append({
                "id": b.get("id", ""),
                "weight": w,
                "tier": b.get("tier", classify_tier(w, l1_thresh, archive_thresh)),
                "last_used": b.get("last_used"),
            })
        weights_data = {
            "meta": {
                "schema_version": 1,
                "author": name,
                "author_email": email,
                "last_updated_by": name,
                "last_updated": today,
                "seeded_from": "MEMORY_INDEX.yaml (v4 migration — weights preserved)",
                "seeded_date": today,
            },
            "blocks": weights_blocks,
        }
        if not dry_run:
            save_yaml(
                weights_data, WEIGHTS_PATH,
                "# Meridian per-developer block weights — gitignored, never committed\n"
                "# Migrated from agent_docs/MEMORY_INDEX.yaml v4 (weights preserved)\n#\n",
            )
            print(f"  Created .agent/weights.yaml ({len(weights_blocks)} blocks, history preserved)")
        else:
            print(f"  Would create .agent/weights.yaml ({len(weights_blocks)} blocks)")
    else:
        print("  .agent/weights.yaml already exists — skipping weights.yaml creation")
        weights_data = load_yaml(WEIGHTS_PATH)

    # Strip weight/tier/last_used from each block
    for b in blocks:
        b.pop("weight", None)
        b.pop("tier", None)
        b.pop("last_used", None)

    # Rebuild meta — remove thresholds/delta (they move to weights.default.yaml)
    index["meta"] = {"format_version": 4.1, "updated": today}
    index["blocks"] = blocks

    if not dry_run:
        _save_index_v41(index, INDEX_PATH)
        print(f"  Updated MEMORY_INDEX.yaml → format_version 4.1 ({len(blocks)} blocks stripped)")
        # Regenerate L1_CONTEXT.md from migrated weights
        if not L1_PATH.exists():
            print("  Generating agent_docs/L1_CONTEXT.md from migrated weights...")
            defaults = load_yaml(DEFAULTS_PATH)
            l1_t, _, _ = load_thresholds(defaults)
            missing = generate_l1_context(weights_data, l1_t)
            l1_count = sum(1 for b in weights_data.get("blocks", []) if float(b.get("weight", 0)) >= l1_t)
            print(f"  Created agent_docs/L1_CONTEXT.md ({l1_count} L1 blocks)")
            _report_missing_l1_content(missing)
    else:
        print("  Would update MEMORY_INDEX.yaml → format_version 4.1")

    print()
    print("  Migration complete. Next steps:")
    print("  1. git rm --cached agent_docs/L1_CONTEXT.md  (untrack from git; file stays on disk)")
    print("  2. Verify: git diff agent_docs/MEMORY_INDEX.yaml (should show only stripped fields)")
    print("  3. Run full session-end update: --used ... --loaded ... to rebuild weights")
    print()


