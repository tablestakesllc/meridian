def main() -> None:
    parser = argparse.ArgumentParser(description="Meridian memory weight manager v4.1")
    parser.add_argument("--used", default=None, help="Block IDs loaded AND actively used this session")
    parser.add_argument("--loaded", default=None, help="Block IDs loaded this session (superset of --used)")
