# ── Standard weight update (--used / --loaded) ────────────────────────────────

def cmd_update(args: argparse.Namespace) -> None:
    if not WEIGHTS_PATH.exists():
        print("  ERROR: .agent/weights.yaml not found — run --seed first.", file=sys.stderr)
        sys.exit(1)

    used_ids = parse_ids(args.used)
    loaded_ids = parse_ids(args.loaded)
    not_in_loaded = used_ids - loaded_ids
    if not_in_loaded:
        print(
            f"  WARNING: --used IDs not in --loaded: {not_in_loaded} — adding automatically.",
            file=sys.stderr,
        )
        loaded_ids |= not_in_loaded

    # Load index blocks for file-glob matching, deps resolution, and dry-run preview
    index_data = load_yaml(INDEX_PATH)
    index_blocks = index_data.get("blocks", [])

    # Item 2: Auto-add blocks whose files: globs match git-modified files (→ loaded only)
    file_matched = match_files_from_git(index_blocks, REPO_ROOT)
    new_from_files = file_matched - loaded_ids
    if new_from_files:
        print(f"\n  FILE-GLOB MATCHES (auto-added to loaded): {', '.join(sorted(new_from_files))}")
        loaded_ids |= new_from_files

    # Item 5: Auto-resolve depends: links transitively (→ loaded delta, not used)
    expanded_ids, auto_deps = resolve_deps(loaded_ids, index_blocks)
    new_from_deps = expanded_ids - loaded_ids
    if new_from_deps:
        print(f"\n  DEP AUTO-INCLUDED ({len(auto_deps)} blocks):")
        for dep_id, parent_id in auto_deps:
            print(f"    {dep_id} (dep of {parent_id})")
        loaded_ids = expanded_ids

    defaults = load_yaml(DEFAULTS_PATH)
    l1_thresh, archive_thresh, delta_cfg = load_thresholds(defaults)
    delta_used = float(delta_cfg.get("loaded_used", 0.10))
    delta_skipped = float(delta_cfg.get("loaded_skipped", 0.00))
    delta_not_loaded = float(delta_cfg.get("not_loaded", -0.05))

    weights_data = load_yaml(WEIGHTS_PATH)
    name, _ = get_git_user()
    blocks = weights_data.get("blocks", [])

    weight_changes: list[tuple[str, float, float, str]] = []
    tier_changes: list[tuple[str, str, str, float, float]] = []

    for block in blocks:
        bid = block.get("id", "")
        old_w = float(block.get("weight", 5.0))
        old_tier = block.get("tier", "L2")

        if bid in used_ids:
            delta = delta_used
            reason = "loaded+used"
            block["last_used"] = args.date
        elif bid in loaded_ids:
            delta = delta_skipped
            reason = "loaded (skipped)"
            block["last_used"] = args.date
        else:
            delta = delta_not_loaded
            reason = "not loaded (decay)"

        new_w = round(max(0.0, min(10.0, old_w + delta)), 2)
        block["weight"] = new_w
        new_tier = classify_tier(new_w, l1_thresh, archive_thresh)
        block["tier"] = new_tier

        if new_w != old_w:
            weight_changes.append((bid, old_w, new_w, reason))
        if new_tier != old_tier:
            tier_changes.append((bid, old_tier, new_tier, old_w, new_w))

    weights_data["meta"]["last_updated"] = args.date
    weights_data["meta"]["last_updated_by"] = name

    # Item 1: Increment maintenance session counter
    w_meta = weights_data.setdefault("meta", {})
    sessions_count = int(w_meta.get("sessions_since_maintenance", 0)) + 1
    w_meta["sessions_since_maintenance"] = sessions_count
    maintenance_interval = int(defaults.get("meta", {}).get("maintenance_interval", 30))

    # ── Report ────────────────────────────────────────────────────────────────
    print(f"\n{'DRY RUN — ' if args.dry_run else ''}Meridian Memory Weight Manager v4.1 — {args.date}")
    print(f"  Loaded: {len(loaded_ids)}  |  Used: {len(used_ids)}  |  Total blocks: {len(blocks)}")

    if tier_changes:
        print("\n  TIER CHANGES:")
        for bid, old_t, new_t, old_w, new_w in tier_changes:
            arrow = "↑ PROMOTED" if new_t == "L1" else ("↓ DEMOTED" if old_t == "L1" else "→ moved")
            print(f"    {arrow:12s} {bid:40s}  {old_t} → {new_t}  ({old_w:.2f} → {new_w:.2f})")
        if not args.dry_run:
            print("  Run with --dry-run to preview the updated L1 before next session.")
    else:
        print("  No tier changes.")

    if weight_changes:
        top = sorted(weight_changes, key=lambda x: abs(x[2] - x[1]), reverse=True)
        print("\n  Top weight changes (up to 10):")
        for bid, old_w, new_w, reason in top[:10]:
            sign = "+" if new_w > old_w else ""
            print(f"    {bid:40s}  {old_w:.2f} → {new_w:.2f}  ({sign}{new_w - old_w:.2f}, {reason})")

    # New blocks in defaults not yet in local weights
    default_ids = {b["id"] for b in defaults.get("blocks", [])}
    local_ids = {b["id"] for b in blocks}
    new_in_defaults = default_ids - local_ids
    if new_in_defaults:
        print(f"\n  RECOMMENDATIONS: {len(new_in_defaults)} new block(s) in defaults not in your weights.")
        print("  Run --check-defaults to review.")

    # Deprecated blocks with high weight (uses MEMORY_INDEX for status)
    index = load_yaml(INDEX_PATH)
    index_map = {b.get("id"): b for b in index.get("blocks", [])}
    deprecated_high = [
        b for b in blocks
        if index_map.get(b["id"], {}).get("status") == "deprecated" and float(b.get("weight", 0)) > 4.0
    ]
    if deprecated_high:
        print("\n  WARNING — DEPRECATED BLOCKS WITH HIGH WEIGHT (> 4.0):")
        for b in deprecated_high:
            print(f"    {b['id']:40s}  weight: {b['weight']:.2f}")

    # Integrity check
    skills_dir = REPO_ROOT / ".agents" / "skills"
    orphaned: list[str] = []
    missing_skill: list[tuple[str, str]] = []
    for b in index.get("blocks", []):
        bid = b.get("id", "")
        local_b = next((lb for lb in blocks if lb["id"] == bid), None)
        if not local_b or local_b.get("tier") == "L1" or b.get("status") == "deprecated":
            continue
        skill = b.get("skill")
        if not skill:
            orphaned.append(bid)
        elif not (skills_dir / str(skill) / "SKILL.md").exists():
            missing_skill.append((bid, str(skill)))
    if orphaned or missing_skill:
        print("\n  INTEGRITY ISSUES:")
        for bid in orphaned:
            print(f"    Orphaned L2 (no skill): {bid}")
        for bid, skill in missing_skill:
            print(f"    Missing skill file: {bid} → {skill}/SKILL.md")
    else:
        print("  Integrity: OK")

    # Health check
    try:
        session_date_obj = date.fromisoformat(args.date)
    except ValueError:
        session_date_obj = date.today()
    stale_days = 90
    active = [b for b in blocks if b.get("tier") != "ARCHIVE"]
    stale = []
    for b in active:
        raw = b.get("last_used")
        if raw:
            try:
                days = (session_date_obj - date.fromisoformat(str(raw))).days
                if days > stale_days:
                    stale.append((b.get("id", "?"), days))
            except ValueError:
                pass
    stale_pct = (len(stale) / len(active) * 100) if active else 0
    if stale_pct >= 40:
        print(
            f"\n  MEMORY HEALTH: {len(stale)}/{len(active)} active blocks "
            f"({stale_pct:.0f}%) unseen for {stale_days}+ days."
        )
        print("  HUMAN ACTION RECOMMENDED: schedule a memory health review.")
    else:
        print(f"  Health: {len(stale)}/{len(active)} stale >{stale_days}d ({stale_pct:.0f}%)")

    # Write
    if not args.dry_run:
        save_yaml(
            weights_data, WEIGHTS_PATH,
            "# Meridian per-developer block weights — gitignored, never committed\n#\n",
        )
        print(f"\n  Wrote {WEIGHTS_PATH}")
        missing = generate_l1_context(weights_data, l1_thresh)
        print(f"  Regenerated {L1_PATH}")
        _report_missing_l1_content(missing)
    else:
        _preview_l1_blocks(weights_data, index_blocks, l1_thresh)
        print("\n  (dry-run: no files written)")

    # Item 1: Maintenance due notice (after write so it's the last thing the agent sees)
    deferred = w_meta.get("maintenance_deferred")
    if sessions_count >= maintenance_interval:
        if deferred:
            # One-time suppression: clear the flag so the notice fires next session
            if not args.dry_run:
                w_meta["maintenance_deferred"] = None
                save_yaml(
                    weights_data, WEIGHTS_PATH,
                    "# Meridian per-developer block weights — gitignored, never committed\n#\n",
                )
            print(f"\n  Maintenance deferred (was: {deferred!r}) — cleared; will prompt next session.")
        else:
            print(f"\n  AGENT MAINTENANCE DUE ({sessions_count} sessions reached).")
            print("  Ask the user: run --check-defaults, --export-defaults, --dry-run, and review depends links.")
            print("  Defer options: [act / next-start / next-end / skip-N]")
            print("  Use --maintenance-reset after acting, or --maintenance-defer <option> to defer.")
    print()


# ── --export-defaults ─────────────────────────────────────────────────────────

def cmd_export_defaults() -> None:
    """Print blocks that have drifted significantly from their seed weight.

    PROMOTE CANDIDATE : local >= seed + export_promote_threshold
    SEED TOO HIGH     : local <= seed - export_demote_threshold
    Output is a human-readable table; maintainer edits weights.default.yaml manually.
    """
    print("\nMeridian Memory Weight Manager v4.1 — export-defaults")
    if not WEIGHTS_PATH.exists():
        print("  .agent/weights.yaml not found — run --seed first.")
        return

    weights = load_yaml(WEIGHTS_PATH)
    defaults = load_yaml(DEFAULTS_PATH)
    meta = defaults.get("meta", {})
    promote_thresh = float(meta.get("export_promote_threshold", 1.5))
    demote_thresh = float(meta.get("export_demote_threshold", 3.0))
    stale_days = 90

    default_map = {b["id"]: b for b in defaults.get("blocks", [])}
    today = date.today()

    promote_candidates: list[tuple] = []
    seed_too_high: list[tuple] = []
    no_action_count = 0

    for block in weights.get("blocks", []):
        bid = block["id"]
        local_w = float(block.get("weight", 5.0))
        d = default_map.get(bid)
        if not d:
            continue
        seed_w = float(d.get("seed_weight", 5.0))
        skill = d.get("skill", "?")
        last_used_raw = block.get("last_used")
        last_used_str = str(last_used_raw) if last_used_raw else "never"
        suggested = round(local_w - 0.5, 1)

        if local_w >= seed_w + promote_thresh:
            promote_candidates.append((bid, skill, local_w, seed_w, suggested, last_used_str))
        elif local_w <= seed_w - demote_thresh:
            if last_used_raw:
                try:
                    days_ago = (today - date.fromisoformat(str(last_used_raw))).days
                    sublabel = "review content" if days_ago < stale_days else "candidate to lower seed or archive"
                except ValueError:
                    sublabel = "review content"
            else:
                sublabel = "candidate to lower seed or archive"
            seed_too_high.append((bid, skill, local_w, seed_w, round(seed_w - 0.5, 1), last_used_str, sublabel))
        else:
            no_action_count += 1

    header = f"  {'Block ID':40s}  {'Skill':20s}  {'Local':6s}  {'Seed':6s}  {'Suggested':9s}  Last Used"
    if promote_candidates:
        print(f"\n  PROMOTE CANDIDATES ({len(promote_candidates)}):")
        print(header)
        for (bid, skill, local_w, seed_w, suggested, last_used) in promote_candidates:
            print(f"  {bid:40s}  {skill:20s}  {local_w:6.2f}  {seed_w:6.2f}  {suggested:9.1f}  {last_used}")

    if seed_too_high:
        print(f"\n  SEED TOO HIGH ({len(seed_too_high)}):")
        print(header + "  Note")
        for (bid, skill, local_w, seed_w, suggested, last_used, sublabel) in seed_too_high:
            print(f"  {bid:40s}  {skill:20s}  {local_w:6.2f}  {seed_w:6.2f}  {suggested:9.1f}  {last_used:12s}  {sublabel}")

    if not promote_candidates and not seed_too_high:
        print("  No blocks outside thresholds — defaults look well-calibrated.")
    else:
        print(f"\n  No action needed: {no_action_count} blocks within threshold.")
        print("\n  Review and update agent_docs/weights.default.yaml, then commit.")
        print("  Each developer will receive a --check-defaults notice on their next session.")
    print()


# ── --calibrate ───────────────────────────────────────────────────────────────

_CALIBRATE_SCALE_FLOOR = 0.6
_CALIBRATE_SCALE_CEILING = 3.0
_CALIBRATE_DEFAULT_PROMOTE = 1.5
_CALIBRATE_DEFAULT_DEMOTE = 3.0


def cmd_calibrate(dry_run: bool) -> None:
    """Calibrate export thresholds from repo git merge activity.

    Counts PR/merge commits on the integration branch over the configured window,
    normalises by distinct author count to get per-developer session rate, applies
    a scale factor (clamped to floor/ceiling), and writes calibrated thresholds
    to agent_docs/weights.default.yaml.

    At the ceiling (high-cadence repos) the demote-by-weight-delta signal is
    effectively disabled; last_used calendar time becomes the primary demotion signal.
    """
    print(f"\n{'DRY RUN — ' if dry_run else ''}Meridian Memory Weight Manager v4.1 — calibrate")
    defaults = load_yaml(DEFAULTS_PATH)
    meta = defaults.get("meta", {})
    window_days = int(meta.get("calibration_window_days", 90))
    baseline_rate = float(meta.get("calibration_baseline_rate", 0.5))
    since = f"{window_days} days ago"

    total_merges = 0
    distinct_authors = 1
    per_dev_rate = baseline_rate

    try:
        merge_result = subprocess.run(
            ["git", "log", "--merges", "--first-parent", f"--since={since}", "--format=%H"],
            capture_output=True, text=True, cwd=REPO_ROOT,
        )
        author_result = subprocess.run(
            ["git", "log", "--merges", "--first-parent", f"--since={since}", "--format=%ae"],
            capture_output=True, text=True, cwd=REPO_ROOT,
        )
        merge_lines = [ln for ln in merge_result.stdout.strip().splitlines() if ln]
        author_lines = [ln for ln in author_result.stdout.strip().splitlines() if ln]
        total_merges = len(merge_lines)
        distinct_authors = max(len(set(author_lines)), 1)
        per_dev_rate = (total_merges / distinct_authors) / window_days
    except (subprocess.CalledProcessError, FileNotFoundError):
        print("  WARNING: git command failed — using default thresholds.")

    scale_factor = max(_CALIBRATE_SCALE_FLOOR, min(_CALIBRATE_SCALE_CEILING, per_dev_rate / baseline_rate))
    export_promote = round(_CALIBRATE_DEFAULT_PROMOTE * scale_factor, 2)
    export_demote = round(_CALIBRATE_DEFAULT_DEMOTE * scale_factor, 2)

    print(f"  Window: {window_days}d | Merges: {total_merges} | Authors: {distinct_authors} | "
          f"Per-dev rate: {per_dev_rate:.3f}/day | Baseline: {baseline_rate}/day | Scale: {scale_factor:.2f}x")
    print(f"  export_promote_threshold → {export_promote}  (default × {scale_factor:.2f})")
    print(f"  export_demote_threshold  → {export_demote}  (default × {scale_factor:.2f})")
    if scale_factor >= _CALIBRATE_SCALE_CEILING:
        print("  NOTE: High-cadence repo — at ceiling. Demotion-by-weight-delta is effectively disabled.")
        print("        last_used >= 90 days is the primary demotion signal.")

    if not dry_run:
        defaults["meta"]["export_promote_threshold"] = export_promote
        defaults["meta"]["export_demote_threshold"] = export_demote
        save_yaml(
            defaults, DEFAULTS_PATH,
            "# Meridian maintainer-curated seed weights\n"
            "# export_promote/demote_threshold: auto-calibrated by --calibrate\n#\n",
        )
        print(f"  Wrote calibrated thresholds to {DEFAULTS_PATH}")
    else:
        print("  (dry-run: no files written)")
    print()


# ── --maintenance-reset / --maintenance-defer ─────────────────────────────────

def cmd_maintenance_reset() -> None:
    """Reset the maintenance session counter to 0 (after running maintenance)."""
    if not WEIGHTS_PATH.exists():
        print("  .agent/weights.yaml not found — run --seed first.")
        return
    weights = load_yaml(WEIGHTS_PATH)
    weights.setdefault("meta", {})["sessions_since_maintenance"] = 0
    weights["meta"]["maintenance_deferred"] = None
    save_yaml(weights, WEIGHTS_PATH, "# Meridian per-developer block weights — gitignored, never committed\n#\n")
    print("  Maintenance counter reset to 0.")
    print()


def cmd_maintenance_defer(value: str) -> None:
    """Defer the maintenance prompt.

    value: 'next-start' | 'next-end' | '<integer N>' (defer by N sessions)
    - next-start / next-end: sets maintenance_deferred flag; SESSION_INIT / session-end
      checklist checks the flag and re-surfaces the prompt.
    - N: sets sessions_since_maintenance = maintenance_interval - N so the prompt
      re-fires in N sessions.
    """
    if not WEIGHTS_PATH.exists():
        print("  .agent/weights.yaml not found — run --seed first.")
        return
    weights = load_yaml(WEIGHTS_PATH)
    meta = weights.setdefault("meta", {})
    if value in ("next-start", "next-end"):
        meta["maintenance_deferred"] = value
        print(f"  Maintenance deferred to: {value}")
    else:
        try:
            n = int(value)
            defaults = load_yaml(DEFAULTS_PATH)
            interval = int(defaults.get("meta", {}).get("maintenance_interval", 30))
            meta["sessions_since_maintenance"] = interval - n
            meta["maintenance_deferred"] = None
            print(f"  Maintenance deferred by {n} sessions (counter set to {interval - n}).")
        except ValueError:
            print(f"  ERROR: invalid defer value '{value}'. Use 'next-start', 'next-end', or an integer N.")
            return
    save_yaml(weights, WEIGHTS_PATH, "# Meridian per-developer block weights — gitignored, never committed\n#\n")
    print()


