"""
.agents/skills/meridian-v4/weight_memory.py — Meridian Memory Weight Manager (v4.1)

Manages per-developer block weights separately from the shared block structure.

FILES:
  agent_docs/MEMORY_INDEX.yaml     — shared block structure (committed, no weights)
  agent_docs/weights.default.yaml  — maintainer-curated seed weights (committed)
  .agent/weights.yaml              — per-developer live weights (gitignored)
  agent_docs/L1_CONTEXT.md         — auto-generated L1 content (gitignored)

STANDARD USAGE (session-end, after final git commit):
    .venv/bin/python .agents/skills/meridian-v4/weight_memory.py \\
        --used   "agent-operating-prefs,release-isolation" \\
        --loaded "agent-operating-prefs,release-isolation,memory-v4-ops" \\
        --date   "YYYY-MM-DD"

FIRST-BOOT / SETUP:
    .venv/bin/python .agents/skills/meridian-v4/weight_memory.py --seed          # create .agent/weights.yaml
    .venv/bin/python .agents/skills/meridian-v4/weight_memory.py --generate-l1   # generate L1_CONTEXT.md

MAINTENANCE:
    .venv/bin/python .agents/skills/meridian-v4/weight_memory.py --check-defaults # review new/changed defaults
    .venv/bin/python .agents/skills/meridian-v4/weight_memory.py --migrate        # one-time v4 → v4.1 migration
    .venv/bin/python .agents/skills/meridian-v4/weight_memory.py --dry-run ...    # preview without writing

WEIGHT DELTAS (from agent_docs/weights.default.yaml meta.delta):
    loaded AND used    : +0.10  (default)
    loaded, NOT used   :  0.00  (default)
    NOT loaded         : -0.05  (default)

TIER THRESHOLDS (from agent_docs/weights.default.yaml meta.thresholds):
    weight >= 8.0  → L1  (auto-loaded via agent_docs/L1_CONTEXT.md)
    weight >= 2.0  → L2  (on-demand via skill trigger keyword)
    weight <  2.0  → ARCHIVE (indexed but not in active loading path)
"""

